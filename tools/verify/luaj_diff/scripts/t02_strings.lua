local s = 'Hello, Lua World'
print('len', #s)
print('upper', s:upper())
print('lower', s:lower())
print('sub', s:sub(1, 5), s:sub(-5), s:sub(8, -6))
print('rep', ('ab'):rep(3), ('ab'):rep(3, '-'))
print('reverse', s:reverse())
print('byte', s:byte(1), s:byte(1, 3))
print('char', string.char(72, 105))
print('find', s:find('Lua'), s:find('Lua', 8), s:find('zz'))
print('find-plain', s:find('L.u'), s:find('L.u', 1, true))
print('match', s:match('(%a+), (%a+)'))
print('match2', s:match('%w+'))
print('gmatch', (function() local o = {} for w in s:gmatch('%a+') do o[#o+1] = w end return table.concat(o, '|') end)())
print('gsub', s:gsub('o', '0'))
print('gsub-fn', s:gsub('%a+', function(w) return '<' .. w .. '>' end))
print('gsub-n', s:gsub('o', '0', 1))
print('format', string.format('%d/%s/%5.2f', 42, 'x', 3.14159))
print('format2', string.format('%x %X %o %e %g', 255, 255, 8, 1234.5, 0.0001))
print('format3', string.format('%q', 'a"b\n'))
print('format4', string.format('%%|%10s|%-10s|', 'r', 'l'))
print('concat', table.concat({ 'a', 'b', 'c' }, '-'))
print('concat-sep-empty', table.concat({ 'a', 'b' }, ''))
print('escape', 'a\tb\nc\\d\"e')
print('longstring', [[line1
line2]])
print('longcomment', 1) --[[ not a comment ]]
print('index', s:sub(1, 1), ('x'):rep(2))
print('select', select('#', 'a', 'b', 'c'), select(2, 'a', 'b', 'c'))
print('tostring-num', ('%s'):format(12))
print('string-meta', getmetatable('').__index == string)
