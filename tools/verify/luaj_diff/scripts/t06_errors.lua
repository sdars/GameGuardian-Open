local function try(f, ...)
  local ok, err = pcall(f, ...)
  if ok then return 'OK:' .. tostring(err) end
  return 'ERR:' .. tostring(err)
end
print('pcall-ok', try(function() return 42 end))
print('pcall-nil-index', try(function() local t = nil return t.x end))
print('pcall-arith', try(function() return 1 + {} end))
print('pcall-concat', try(function() return 'a' .. nil end))
print('pcall-call', try(function() local f = 5 return f() end))
print('pcall-error-str', try(function() error('boom') end))
print('pcall-error-table', try(function() error({ code = 7 }) end))
print('pcall-error-num', try(function() error(42) end))
print('pcall-assert', try(function() assert(false) end))
print('pcall-assert-msg', try(function() assert(nil, 'custom assert') end))
print('pcall-assert-ok', try(function() assert(1 == 1, 'x') return 'fine' end))
print('xpcall', xpcall(function() error('x') end, function(e) return 'H:' .. tostring(e) end))
print('xpcall-ok', xpcall(function() return 'v' end, function(e) return 'H' end))
print('error-level', try(function() error('lvl', 0) end))
print('error-level2', try(function() error('lvl2', 2) end))
print('pcall-nested', try(function() return (function() error('inner') end)() end))
local ok, e = pcall(function() local t = setmetatable({}, { __index = function() error('mt-err') end }) return t.x end)
print('mt-error', ok, tostring(e))
print('pcall-method', try(function() local t = {} return t:nope() end))
print('select-n', select('#', pcall(function() return 1 end)))
print('pcall-returns', pcall(function() return 1, 2 end))
