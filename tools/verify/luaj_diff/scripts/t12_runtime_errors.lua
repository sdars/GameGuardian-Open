-- Runtime diagnostics emitted by the VM itself.
local function try(f)
  local ok, err = pcall(f)
  if ok then return 'OK' end
  return tostring(err)
end
print('nil-index', try(function() return (nil).x end))
print('nil-call', try(function() return (nil)() end))
print('num-index', try(function() return (5).x end))
print('str-index-num', try(function() return ('x')[1] end))
print('num-call', try(function() return (5)() end))
print('arith-nil', try(function() return nil + 1 end))
print('arith-str', try(function() return 'x' + 1 end))
print('concat-nil', try(function() return 'x' .. nil end))
print('concat-table', try(function() return {} .. 'x' end))
print('len-nil', try(function() return #nil end))
print('cmp-str-num', try(function() return 'x' < 1 end))
print('cmp-table', try(function() return {} < {} end))
print('for-iter', try(function() for k in 5 do end end))
print('tostring-none', try(function() local u = nil return u.x end))
print('bad-index-fn', try(function() local t = setmetatable({}, { __index = 5 }) return t.x end))
print('bad-newindex', try(function() local t = setmetatable({}, { __newindex = 5 }) t.x = 1 end))
print('bad-call-meta', try(function() local t = setmetatable({}, { __call = 5 }) return t() end))
print('bad-arith-meta', try(function() local t = setmetatable({}, { __add = 5 }) return t + 1 end))
print('bad-len-meta', try(function() local t = setmetatable({}, { __len = 5 }) return #t end))
print('bad-tostring-meta', try(function() local t = setmetatable({}, { __tostring = 5 }) return tostring(t) end))
print('bad-pairs', try(function() return pairs(5) end))
print('bad-ipairs', try(function() return ipairs(5) end))
print('bad-select', try(function() return select('#') end))
print('bad-tonumber', try(function() return tonumber() end))
print('bad-rawset', try(function() rawset(5, 'a', 1) end))
print('bad-rawget', try(function() return rawget(5, 'a') end))
print('bad-setmetatable', try(function() return setmetatable(5, {}) end))
print('bad-getmetatable', try(function() return getmetatable(5) end))
print('bad-table-sort', try(function() table.sort({ 1, 'x' }) end))
print('bad-table-insert', try(function() table.insert(nil, 1) end))
print('bad-table-concat', try(function() return table.concat({ 1, {} }) end))
print('bad-string-sub', try(function() return ('x'):sub('a') end))
print('bad-string-rep', try(function() return ('x'):rep(-1) end))
print('bad-string-format', try(function() return string.format('%d', 'x') end))
print('bad-string-find', try(function() return ('x'):find('x', 'a') end))
print('bad-math-max', try(function() return math.max() end))
print('bad-math-random', try(function() return math.random(1, 0) end))
print('bad-os-time', try(function() return os.time('x') end))
print('bad-coroutine', try(function() return coroutine.resume(5) end))
print('bad-coroutine2', try(function() return coroutine.yield() end))
